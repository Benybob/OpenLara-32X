#!/usr/bin/env python3
"""Repack the repository's GBA PCM effects as a deduplicated 11,025 Hz IMA bank.

No new game-data download is required. Packed geometry is left untouched.
The encoder and runtime decoder use low-nibble-first IMA/DVI ADPCM, reset to
predictor/index zero at the start of each independently seekable effect.
"""
from pathlib import Path
import hashlib
import json
import struct

STEPS = [7,8,9,10,11,12,13,14,16,17,19,21,23,25,28,31,34,37,41,45,50,55,60,66,73,80,88,97,107,118,130,143,157,173,190,209,230,253,279,307,337,371,408,449,494,544,598,658,724,796,876,963,1060,1166,1282,1411,1552,1707,1878,2066,2272,2499,2749,3024,3327,3660,4026,4428,4871,5358,5894,6484,7132,7845,8630,9493,10442,11487,12635,13899,15289,16818,18500,20350,22385,24623,27086,29794,32767]
INDEX = [-1,-1,-1,-1,2,4,6,8]

def encode(pcm):
    pred = idx = 0
    nibbles = []
    for value in pcm:
        step = STEPS[idx]
        delta = value - pred
        code = 8 if delta < 0 else 0
        delta = abs(delta)
        diff = step >> 3
        for bit, amount in ((4,step),(2,step>>1),(1,step>>2)):
            if delta >= amount:
                code |= bit; delta -= amount; diff += amount
        pred = max(-32768,min(32767,pred + (-diff if code & 8 else diff)))
        idx = max(0,min(88,idx+INDEX[code&7]))
        nibbles.append(code)
    if len(nibbles)&1: nibbles.append(0)
    return bytes(nibbles[i] | (nibbles[i+1]<<4) for i in range(0,len(nibbles),2))

def main():
    root = Path(__file__).resolve().parents[2]
    platform = root/'src/platform/32x'
    bank = bytearray(); unique = {}; samples = []; levels = []; source_hashes = {}
    for name in ('GYM','LEVEL1','LEVEL2'):
        source = root/f'src/platform/gba/data/{name}.PKD'
        d = source.read_bytes(); source_hashes[name] = hashlib.sha256(d).hexdigest()
        map_pos, info_pos, data_pos, offsets_pos = struct.unpack_from('<4I',d,156)
        count = struct.unpack_from('<H',d,30)[0]
        sound_map = struct.unpack_from('<256H',d,map_pos)
        infos = [struct.unpack_from('<4H',d,o) for o in range(info_pos,data_pos,8)]
        assert all(i==65535 or i<len(infos) for i in sound_map)
        ids=[]
        for i in range(count):
            offset=struct.unpack_from('<I',d,offsets_pos+4*i)[0]
            length=struct.unpack_from('<I',d,data_pos+offset)[0]
            raw=d[data_pos+offset+4:data_pos+offset+4+length]
            assert len(raw)==length and length>0 and length%2==0
            key=hashlib.sha256(raw).digest()
            if key not in unique:
                # Average adjacent 22,050 Hz unsigned PCM samples before decimation.
                pcm=[(raw[j]+raw[j+1]-256)*128 for j in range(0,length,2)]
                encoded=encode(pcm)
                while len(bank)&3: bank.append(0)
                unique[key]=len(samples)
                samples.append((len(bank),len(pcm)))
                bank.extend(encoded)
            ids.append(unique[key])
        assert all(info[0]+max(1,(info[3]>>2)&15)<=count for info in infos if info[1])
        levels.append((sound_map,infos,ids))
    while len(bank)&3: bank.append(0)
    (platform/'data/sfx-ima.bin').write_bytes(bank)
    lines=['// Generated by tools/32x/pack_sfx.py. Source data remains upstream game data.',
           'struct MarsSampleAsset { uint32 offset, length; };',
           'struct MarsSoundLevel { const uint16* map; const SoundInfo* infos; const uint8* ids; uint32 count; };',
           'static const uint16 imaDelta[89][8] = {']
    for step in STEPS:
        values=[(step>>3)+(step if code&4 else 0)+(step>>1 if code&2 else 0)+(step>>2 if code&1 else 0) for code in range(8)]
        lines.append('    {'+','.join(map(str,values))+'},')
    lines += ['};','static const MarsSampleAsset sampleAssets[] = {']
    lines += ['    {%d, %d},'%s for s in samples]; lines += ['};']
    for i,(maps,infos,ids) in enumerate(levels):
        lines += [f'static const uint16 soundMap{i}[] = {{'+','.join(str(x) for x in maps)+'};',
                  f'static const SoundInfo soundInfos{i}[] = {{']
        lines += ['    {%d,%d,%d,%d},'%info for info in infos];lines+=['};']
        lines += [f'static const uint8 sampleIds{i}[] = {{'+','.join(str(x) for x in ids)+'};']
    lines += ['static const MarsSoundLevel soundLevels[] = {']
    lines += [f'    {{soundMap{i},soundInfos{i},sampleIds{i},{len(level[2])}}},' for i,level in enumerate(levels)]
    lines += ['};','']
    (platform/'sound_assets.h').write_text('\n'.join(lines))
    worker = ['// Generated exact IMA tables for the two 68000 workers.',
              'static const uint16_t mwDelta[89][8] MW_TABLE = {']
    for step in STEPS:
        values=[(step>>3)+(step if code&4 else 0)+(step>>1 if code&2 else 0)+(step>>2 if code&1 else 0) for code in range(8)]
        worker.append('{'+','.join(map(str,values))+'},')
    worker += ['};','static const uint8_t mwNext[89][8] MW_TABLE = {']
    for index in range(89):
        worker.append('{'+','.join(str(max(0,min(88,index+INDEX[code]))) for code in range(8))+'},')
    worker += ['};','']
    (platform/'src-md/worker_tables.h').write_text('\n'.join(worker))
    fast = ['| Generated signed deltas and next-state row offsets.']
    for index, step in enumerate(STEPS):
        for code in range(16):
            diff=(step>>3)+(step if code&4 else 0)+(step>>1 if code&2 else 0)+(step>>2 if code&1 else 0)
            fast += [f'.long {-diff if code&8 else diff}',
                     f'.word {max(0,min(88,index+INDEX[code&7]))*128},0']
    (platform/'src-md/worker_fast_tables.inc').write_text('\n'.join(fast)+'\n')
    stats={'sample_rate':11025,'codec':'IMA/DVI ADPCM, low nibble first','unique_effects':len(samples),'encoded_bytes':len(bank),'decoded_samples':sum(s[1] for s in samples),'source_sha256':source_hashes,'bank_sha256':hashlib.sha256(bank).hexdigest()}
    (platform/'data/sfx-manifest.json').write_text(json.dumps(stats,indent=2)+'\n')
    print(json.dumps(stats,indent=2))

if __name__=='__main__': main()
